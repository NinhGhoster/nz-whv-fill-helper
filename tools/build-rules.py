#!/usr/bin/env python3
"""
Convert a Lightning Autofill export into rules for the fill helper.

Usage:
    python3 tools/build-rules.py path/to/your-export.csv
    python3 tools/build-rules.py lightning-autofill.example.csv --example

Without --example this writes extension/rules.json, extension/rules.js and
rules-report.md. Those files contain your personal answers: keep them out of
git.

With --example it writes extension/rules.example.json,
extension/rules.example.js and rules-report.example.md instead. Only the
synthetic example should be committed.
"""

import csv
import json
import re
import sys
import datetime
from pathlib import Path

PROFILE_PAGE = {
    "c2": ("Personal1", "Personal1.aspx"),
    "c3": ("Personal2", "Personal2.aspx"),
    "c4": ("Medical1", "Medical1.aspx"),
    "c5": ("Character", "Character.aspx"),
    "c6": ("WorkingHolidaySpecific", "WorkingHolidaySpecific.aspx"),
    "c7": ("Submit", "Submit.aspx"),
    "c8": ("Payment", "Payment.aspx"),
}

TYPE = {"0": "text", "2": "select", "3": "checkbox"}

PII_FIELDS = (
    "passport",
    "familyname",
    "givenname",
    "email",
    "address",
    "payer",
    "countrydropdown",
    "dateofbirth",
    "intendedtravel",
)


def unquote(s: str) -> str:
    s = s.strip()
    if len(s) >= 2 and s[0] == '"' and s[-1] == '"':
        return s[1:-1]
    return s


def mask(field_name: str, value: str) -> str:
    low = field_name.lower()
    if any(k in low for k in PII_FIELDS):
        if len(value) <= 2:
            return value
        return value[0] + "*" * (len(value) - 1)
    return value


def main() -> int:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    example = "--example" in sys.argv[1:]

    if len(args) != 1:
        print(__doc__)
        return 2

    src = Path(args[0])
    root = Path(__file__).resolve().parent.parent
    ext = root / "extension"
    suffix = ".example" if example else ""
    out = ext / f"rules{suffix}.json"
    out_js = ext / f"rules{suffix}.js"
    report = root / f"rules-report{suffix}.md"

    rows = list(csv.reader(src.open(newline="", encoding="utf-8-sig")))

    pages: dict[str, dict] = {}
    bad = []

    for row in rows:
        if len(row) < 7:
            continue
        rid, typ, name, value, _site, _mode, profile = row[:7]
        if not re.fullmatch(r"r\d+", rid) or typ not in TYPE:
            continue

        page = PROFILE_PAGE.get(profile)
        if not page:
            bad.append((rid, profile))
            continue

        field = unquote(name)
        if not field:
            continue

        val = unquote(value) if typ in ("2",) else value
        page_id, page_file = page

        entry = {"name": field, "type": TYPE[typ], "value": val}
        pages.setdefault(page_id, {"profile": profile, "file": page_file, "fields": []})
        pages[page_id]["fields"].append(entry)

    doc = {
        "source": src.name,
        "generated": datetime.datetime.now().isoformat(timespec="seconds"),
        "note": "Field names are the real ASP.NET name attributes from the INZ form.",
        "pages": pages,
    }

    out.write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    # A JS copy so the content script does not need fetch() or a
    # web_accessible_resources entry. Loaded before content.js by the manifest.
    out_js.write_text(
        "/* Generated by tools/build-rules.py — do not edit by hand. */\n"
        "window.__NZWHV_RULES__ = "
        + json.dumps(doc, indent=2, ensure_ascii=False)
        + ";\n",
        encoding="utf-8",
    )

    lines = ["# Rules extracted from the export", "", f"Source: `{src.name}`", ""]
    for page_id, page in pages.items():
        lines.append(f"## {page_id} — `{page['file']}` ({len(page['fields'])} fields)")
        lines.append("")
        lines.append("| # | type | field name | value |")
        lines.append("|---|---|---|---|")
        for i, f in enumerate(page["fields"], 1):
            short = f["name"].replace("_ctl0:ContentPlaceHolder1:", "…:")
            lines.append(
                f"| {i} | {f['type']} | `{short}` | {mask(f['name'], f['value'])} |"
            )
        lines.append("")

    report.write_text("\n".join(lines), encoding="utf-8")

    total = sum(len(p["fields"]) for p in pages.values())
    print(f"wrote {out.name} + {out_js.name} — {total} fields across {len(pages)} pages")
    for page_id, page in pages.items():
        print(f"  {page_id:24} {len(page['fields']):>3} fields")
    if bad:
        print("skipped:", bad)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
